/** Plugin-local launchers (issue #276) — the rules, with no I/O.
 *
 *  A plugin that ships a CLI would otherwise have its skills fall back to `npx -y <pkg>@<version>`,
 *  which fetches and runs code at call time and never matches a permission rule written for the bare
 *  command. A launcher is `bin/<name>`: an extensionless shim that runs an entry inside the package,
 *  so the version is the plugin's by construction.
 *
 *  Claude Code puts a plugin's `bin/` on the Bash tool's `PATH` (code.claude.com/docs/en/plugins/components.md,
 *  "Executables"), after the user's own `PATH`. Verified for an npm-sourced install only. Hooks, MCP
 *  processes, Cursor, Codex, Copilot CLI and Windows are untested. */

/** One declared launcher: the command name, and the entry it runs relative to the plugin root. */
export interface LauncherEntry {
	name: string
	entry: string
}

/** The mode a launcher must have; a file that is not executable is not a command. */
export const LAUNCHER_MODE = 0o755

/** Where launchers live, relative to the plugin root. */
export const LAUNCHER_DIR = 'bin'

const HEADER = '# Generated by `universal-plugin plugin build` from plugin.json. Edit plugin.json, not this file.'

const NAME_PATTERN = /^[a-z0-9][a-z0-9._-]*$/i

/** Reads the `launchers` declaration: a map from command name to entry path. A malformed declaration
 *  or entry is an error, never a silent skip: a launcher the author declared and the build dropped is
 *  a skill that calls a command that does not exist. */
export function parseLauncherEntries(declaration: unknown): { entries: LauncherEntry[]; errors: string[] } {
	if (declaration === undefined) return { entries: [], errors: [] }
	if (declaration === null || typeof declaration !== 'object' || Array.isArray(declaration)) {
		return { entries: [], errors: ['launchers is not a map from command name to entry — no launcher was written'] }
	}
	const entries: LauncherEntry[] = []
	const errors: string[] = []
	for (const [name, value] of Object.entries(declaration as Record<string, unknown>)) {
		if (!NAME_PATTERN.test(name)) {
			errors.push(`launchers "${name}" is not a plain command name (letters, digits, ".", "_" and "-")`)
			continue
		}
		if (typeof value !== 'string') {
			errors.push(`launchers "${name}" must map to an entry path inside the plugin`)
			continue
		}
		const entry = normalizeEntry(value)
		if (entry === null) errors.push(`launchers "${name}" entry "${value}" is not a path inside the plugin`)
		else entries.push({ name, entry })
	}
	return { entries, errors }
}

/** A `/`-separated path relative to the plugin root, without `./`; `null` when it is empty, absolute
 *  or climbs out of the root. */
function normalizeEntry(p: string): string | null {
	if (p.startsWith('/') || /^[a-z]:/i.test(p)) return null
	const segments: string[] = []
	for (const segment of p.split(/[\\/]/)) {
		if (segment === '' || segment === '.') continue
		if (segment !== '..') segments.push(segment)
		else if (segments.length === 0) return null
		else segments.pop()
	}
	return segments.length === 0 ? null : segments.join('/')
}

/** Single-quotes a value for a POSIX shell. */
function shellQuote(value: string): string {
	return `'${value.replace(/'/g, `'\\''`)}'`
}

/** The shim for one launcher. The entry is resolved from the shim's own location, so the launcher
 *  works from any directory and through any `PATH` entry. When the entry is missing (a git-sourced
 *  install that was not built) it exits 127 and names the pinned `npx` that would run instead; the
 *  version is read from `plugin.json` at run time, so `plugin version` never has to stamp the shim. */
export function composeLauncher({ name, entry }: LauncherEntry, packageName: string | null): string {
	const fallback =
		packageName === null
			? ''
			: `  version=$(sed -n 's/^[[:space:]]*"version":[[:space:]]*"\\([^"]*\\)".*/\\1/p' "$root/plugin.json" 2>/dev/null | head -n 1)
  echo "To run this version without a build: npx -y ${packageName}\${version:+@$version} ..." >&2
`
	return `#!/bin/sh
${HEADER}
root=$(cd -- "$(dirname -- "$0")/.." && pwd)
entry="$root/${entry}"
if [ ! -f "$entry" ]; then
  echo ${shellQuote(`${name}: ${entry} is missing. This copy of the plugin was not built.`)} >&2
${fallback}  exit 127
fi
exec node "$entry" "$@"
`
}

/** How the file on disk compares with the freshly composed launcher.
 *
 *  - `unchanged` — identical content, and executable.
 *  - `missing` — no file on disk.
 *  - `stale` — the content differs, or the file is not executable. */
export type LauncherComparison = 'unchanged' | 'missing' | 'stale'

export function compareLauncher(
	existing: { content: string; mode: number } | null,
	composed: string,
): LauncherComparison {
	if (existing === null) return 'missing'
	const executable = (existing.mode & 0o111) === 0o111
	return existing.content === composed && executable ? 'unchanged' : 'stale'
}

/** A warning when the package's `files` list leaves `bin/` out, so a launcher would be built and never
 *  published. `null` when `files` is absent (npm then ships everything not ignored) or covers it. */
export function publishedFilesWarning(files: unknown): string | null {
	if (!Array.isArray(files)) return null
	const covered = files.some((f) => typeof f === 'string' && /^(\.\/)?bin(\/.*)?\/?$/.test(f.replace(/\/+$/, '')))
	return covered
		? null
		: 'package.json "files" does not list "bin" — the launchers would be built but not published with the package'
}
